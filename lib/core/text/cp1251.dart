// cp1252 chars that an Icecast "latin1→utf8" double-encode may produce for bytes 0x80..0x9F.
const _cp1252Reverse = <int, int>{0x20AC:0x80,0x201A:0x82,0x0192:0x83,0x201E:0x84,0x2026:0x85,0x2020:0x86,0x2021:0x87,
