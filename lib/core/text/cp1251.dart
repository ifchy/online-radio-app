// windows-1251 repair for ICY titles.
//
// Media3's IcyDecoder tries UTF-8 and falls back to ISO-8859-1, so a station
// that sends windows-1251 bytes arrives as U+0080..U+00FF characters
// ('Àðòèñò - Ïåñåí'). Each such character is exactly one original byte, so
// the text can be turned back into bytes and decoded as windows-1251.
//
// The table was generated from Python's `cp1251` codec (01-RESEARCH.md,
// "cp1251 repair"); do not retype it by hand.

